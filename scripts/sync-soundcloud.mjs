#!/usr/bin/env node
/**
 * Regenerates apps/web/public/music/tracks.json from public SoundCloud playlists (merged in order,
 * duplicates removed).
 *
 *   node scripts/sync-soundcloud.mjs [playlist-url ...]      (default: the playlists below)
 *
 * Skipped: tracks whose title is Russian (Cyrillic without Ukrainian-only letters, or with ы/э/ъ/ё),
 * and tracks SoundCloud won't stream in full (policy BLOCK = unavailable, SNIP = 30 s preview).
 * Uses the same public api-v2 the soundcloud.com site uses (client_id scraped from its bundle).
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const DEFAULT_PLAYLISTS = [
  'https://soundcloud.com/trippleflow/sets/larping-playlist',
  'https://soundcloud.com/alan-gontarz/sets/larp-playlist',
];
// Share links carry tracking parameters (?si=…&utm_…): keep just the playlist address.
const PLAYLISTS = (process.argv.length > 2 ? process.argv.slice(2) : DEFAULT_PLAYLISTS).map(
  (u) => u.split('?')[0],
);
const OUT = fileURLToPath(new URL('../apps/web/public/music/tracks.json', import.meta.url));
const UA = { 'user-agent': 'Mozilla/5.0' };

export function isRussianTitle(title) {
  if (!/[Ѐ-ӿ]/.test(title)) return false;
  if (/[ыэъёЫЭЪЁ]/.test(title)) return true;
  return !/[іїєґІЇЄҐ]/.test(title);
}

async function text(url) {
  const r = await fetch(url, { headers: UA });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.text();
}

async function clientId(html) {
  const scripts = [...html.matchAll(/https:\/\/a-v2\.sndcdn\.com\/assets\/[^"]+\.js/g)].map((m) => m[0]);
  for (const s of scripts.reverse()) {
    const m = /client_id:"([A-Za-z0-9]+)"/.exec(await text(s));
    if (m) return m[1];
  }
  throw new Error('client_id not found');
}

const api = (path) => `https://api-v2.soundcloud.com${path}${path.includes('?') ? '&' : '?'}client_id=${cid}`;

let cid = null;
const ids = [];
for (const url of PLAYLISTS) {
  const html = await text(url);
  cid ??= await clientId(html);
  const playlistId = /soundcloud:\/\/playlists:(\d+)/.exec(html)?.[1];
  if (!playlistId) throw new Error(`playlist id not found: ${url}`);
  const playlist = JSON.parse(await text(api(`/playlists/${playlistId}`)));
  const before = ids.length;
  for (const t of playlist.tracks) if (!ids.includes(t.id)) ids.push(t.id);
  console.log(`${url}: ${playlist.tracks.length} tracks (${ids.length - before} new)`);
}
const byId = new Map();
for (let i = 0; i < ids.length; i += 50) {
  for (const t of JSON.parse(await text(api(`/tracks?ids=${ids.slice(i, i + 50).join(',')}`))))
    byId.set(t.id, t);
}

const skipped = [];
const tracks = [];
for (const id of ids) {
  const t = byId.get(id);
  if (!t) continue;
  if (isRussianTitle(t.title)) skipped.push(`ru    ${t.title}`);
  else if (t.policy === 'BLOCK' || t.policy === 'SNIP')
    skipped.push(`${t.policy.toLowerCase().padEnd(5)} ${t.title}`);
  else {
    const art = t.artwork_url ?? t.user?.avatar_url;
    tracks.push({
      id: `sc-${t.id}`,
      title: t.title,
      artist: t.user?.username,
      sc: t.permalink_url,
      ...(art ? { cover: art.replace('-large.', '-t300x300.') } : {}),
    });
  }
}

const note = `Generated by scripts/sync-soundcloud.mjs from ${PLAYLISTS.join(' + ')}. Played in random order.`;
await writeFile(OUT, JSON.stringify({ note, shuffle: true, tracks }, null, 2) + '\n');
console.log(`${tracks.length} tracks written, ${skipped.length} skipped:`);
for (const s of skipped) console.log('  ' + s);
