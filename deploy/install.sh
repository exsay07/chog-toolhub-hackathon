#!/usr/bin/env bash
# Chog Toolhub — install / start the production stack (run as the "chog" user, from the repo root):
#   bash deploy/install.sh
# Creates deploy/.env (random database password + your Cloudflare Tunnel token, typed hidden) and
# deploy/.env.production (your domain), builds, starts, and waits until the site answers. Safe to re-run:
# existing settings are kept.
set -euo pipefail
cd "$(dirname "$0")"

DOMAIN_DEFAULT=chogtoolhub.space
say() { printf '\n\033[1;35m==> %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "Docker is missing — run deploy/setup-vps.sh as root first"
docker info >/dev/null 2>&1 || die "no access to Docker — log out and in again (docker group), or run setup-vps.sh"

if [ ! -f .env ]; then
  say "Secrets (deploy/.env)"
  echo "Paste the Cloudflare Tunnel token (Zero Trust → Networks → Tunnels → your tunnel)."
  echo "It is the long string after --token. Input is hidden."
  read -rsp "Tunnel token: " TOKEN
  echo
  [ ${#TOKEN} -gt 50 ] || die "that does not look like a tunnel token"
  umask 077
  cat >.env <<EOF
# Generated by deploy/install.sh — never commit or share.
POSTGRES_PASSWORD=$(openssl rand -hex 24)
CLOUDFLARE_TUNNEL_TOKEN=$TOKEN
EOF
  unset TOKEN
  echo "deploy/.env created (database password generated)."
fi

if [ ! -f .env.production ]; then
  say "App settings (deploy/.env.production)"
  read -rp "Domain [$DOMAIN_DEFAULT]: " DOMAIN
  DOMAIN=${DOMAIN:-$DOMAIN_DEFAULT}
  DOMAIN=${DOMAIN#https://}
  DOMAIN=${DOMAIN%/}
  umask 077
  sed "s#^APP_ORIGIN=.*#APP_ORIGIN=https://$DOMAIN#" .env.production.example >.env.production
  echo "deploy/.env.production created for https://$DOMAIN (add API keys there later if you like)."
fi
chmod 600 .env .env.production
mkdir -p backups

say "Build and start (the first build takes a few minutes)"
docker compose up -d --build

say "Waiting for the app"
for _ in $(seq 1 60); do
  if docker compose exec -T app node -e "fetch('http://127.0.0.1:8787/readyz').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))" 2>/dev/null; then
    ok=1
    break
  fi
  sleep 5
done
docker compose ps
[ "${ok:-}" = 1 ] || { docker compose logs --tail 60 app; die "the app did not become ready — see the log above"; }

ORIGIN=$(grep '^APP_ORIGIN=' .env.production | cut -d= -f2-)
cat <<EOF

────────────────────────────────────────────────────────────────────────────
 Running.  Open $ORIGIN
   (Cloudflare → Zero Trust → Tunnels should now show the tunnel as HEALTHY)

 Useful:
   docker compose -f deploy/docker-compose.yml logs -f app     live log
   bash deploy/update.sh                                       pull the latest code and restart
   ls deploy/backups/daily                                     database backups (daily, kept 7/4/6)
────────────────────────────────────────────────────────────────────────────
EOF
