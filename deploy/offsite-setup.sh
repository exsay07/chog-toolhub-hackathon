#!/usr/bin/env bash
# Chog Toolhub — copy database backups off the server to Cloudflare R2 (run once as "chog"):
#   bash deploy/offsite-setup.sh
# Asks for the R2 bucket credentials (the secret is typed hidden), stores them in deploy/.r2.env (mode 600),
# uploads the current backups as a test, and schedules a daily upload (cron, 01:30 server time).
set -euo pipefail
cd "$(dirname "$0")"
die() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

command -v docker >/dev/null || die "Docker is missing"
echo "Cloudflare → R2 → your bucket; R2 → Manage API tokens → token with Object Read & Write on that bucket."
read -rp "Account ID (32 hex characters, shown on the R2 overview page): " ACCOUNT
read -rp "Bucket name [chog-backups]: " BUCKET
BUCKET=${BUCKET:-chog-backups}
read -rp "Access Key ID: " KEY_ID
read -rsp "Secret Access Key (hidden): " SECRET
echo
[[ $ACCOUNT =~ ^[0-9a-f]{32}$ ]] || die "Account ID should be 32 hex characters"
[[ $BUCKET =~ ^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$ ]] || die "invalid bucket name"
[ ${#KEY_ID} -ge 20 ] && [ ${#SECRET} -ge 40 ] || die "the access key / secret look too short — paste them once"

umask 077
cat >.r2.env <<EOF
# Generated by deploy/offsite-setup.sh — never commit or share.
R2_BUCKET=$BUCKET
RCLONE_CONFIG_R2_TYPE=s3
RCLONE_CONFIG_R2_PROVIDER=Cloudflare
RCLONE_CONFIG_R2_ENDPOINT=https://$ACCOUNT.r2.cloudflarestorage.com
RCLONE_CONFIG_R2_ACCESS_KEY_ID=$KEY_ID
RCLONE_CONFIG_R2_SECRET_ACCESS_KEY=$SECRET
RCLONE_CONFIG_R2_NO_CHECK_BUCKET=true
EOF
chmod 600 .r2.env
unset SECRET KEY_ID

echo "==> Test upload"
bash ./offsite-backup.sh || die "upload failed — check the credentials (deploy/.r2.env) and that the bucket exists"

echo "==> Daily schedule (01:30)"
JOB="30 1 * * * bash $(pwd)/offsite-backup.sh >> $HOME/offsite-backup.log 2>&1"
( crontab -l 2>/dev/null | grep -v 'offsite-backup.sh' ; echo "$JOB" ) | crontab -
crontab -l | grep offsite-backup.sh
echo "Done. Backups are now copied to R2 bucket '$BUCKET' every night (log: ~/offsite-backup.log)."
