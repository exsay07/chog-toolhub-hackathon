import {
  Bell,
  CandlestickChart,
  ChevronRight,
  Crosshair,
  Eye,
  Flame,
  Gauge,
  House,
  Image,
  LayoutGrid,
  Lock,
  LockOpen,
  LogOut,
  Moon,
  PanelLeftClose,
  PanelLeftOpen,
  Plus,
  Search,
  Settings,
  Square,
  Star,
  Trophy,
  Sun,
  Trash2,
  Wallet,
  Zap,
  type LucideIcon,
} from 'lucide-react';

/** Lucide icons (MIT) behind a small name-based API. */
const ICONS: Record<string, LucideIcon> = {
  welcome: House,
  dashboard: LayoutGrid,
  terminal: CandlestickChart,
  sniper: Crosshair,
  tracker: Eye,
  nft: Image,
  top: Trophy,
  mints: Flame,
  perps: Gauge,
  portfolio: Wallet,
  settings: Settings,
  lock: Lock,
  unlock: LockOpen,
  stop: Square,
  search: Search,
  star: Star,
  sun: Sun,
  moon: Moon,
  logout: LogOut,
  plus: Plus,
  trash: Trash2,
  chevron: ChevronRight,
  bolt: Zap,
  bell: Bell,
  'sidebar-close': PanelLeftClose,
  'sidebar-open': PanelLeftOpen,
};

export function Icon({ name, size = 16, className }: { name: string; size?: number; className?: string }) {
  const C = ICONS[name] ?? Square;
  return <C size={size} strokeWidth={1.75} className={className} aria-hidden />;
}
